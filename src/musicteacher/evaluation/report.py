"""Build the results report from the run JSONs in `evals/results/`.

For each condition, the most recent full run (no --limit) is used. The report shows:
- the main table: every metric per condition, mean and 95% bootstrap CI;
- breakdowns per language, per question type, cross-lingual subset, and dev vs held-out;
- paired differences for the research questions (same questions, two conditions): the bootstrap CI
  of the mean per-question difference. If it contains 0, the gap is not distinguishable from noise.

Every number comes from the JSON files: nothing is typed by hand.

Usage: uv run python -m musicteacher.evaluation.report
"""

import json
from pathlib import Path

import numpy as np

from musicteacher.config import get_settings
from musicteacher.evaluation.metrics import bootstrap_ci, summarise
from musicteacher.evaluation.run import CONDITIONS, METRICS

COMPARISONS = [
    ("C1", "C0", "RAG (dense) vs no retrieval"),
    ("C3", "C1", "H1: hybrid vs dense"),
    ("C2", "C1", "BM25 vs dense"),
    ("C4", "C3", "H2: reranker on top of hybrid"),
    ("C4", "C1", "RQ1: hybrid + reranker vs dense"),
]
LABELS = {
    "recall_at_5": "Recall@5",
    "article_recall_at_5": "Article recall@5",
    "mrr_at_10": "MRR@10",
    "correctness": "Correctness",
    "faithfulness": "Faithfulness",
    "relevancy": "Relevancy",
}


def latest_full_runs(results_dir: Path) -> dict[str, dict]:
    runs: dict[str, dict] = {}
    for path in sorted(results_dir.glob("C*_*.json")):
        result = json.loads(path.read_text(encoding="utf-8"))
        if result.get("limit") is None and result["condition"] in CONDITIONS:
            result["_file"] = path.name
            runs[result["condition"]] = result  # sorted by name: the latest timestamp wins
    return dict(sorted(runs.items()))


def paired_difference(a: dict, b: dict, metric: str, seed: int = 42) -> dict:
    """Mean of (a - b) over the questions scored in both runs, with a bootstrap CI."""
    b_values = {q["id"]: q.get(metric) for q in b["questions"]}
    diffs = [
        q[metric] - b_values[q["id"]]
        for q in a["questions"]
        if q.get(metric) is not None and b_values.get(q["id"]) is not None
    ]
    return bootstrap_ci(diffs, seed=seed)


def fmt(stat: dict) -> str:
    if stat["mean"] is None:
        return "–"
    return f"{stat['mean']:.2f} [{stat['ci_low']:.2f}, {stat['ci_high']:.2f}]"


def fmt_diff(stat: dict) -> str:
    if stat["mean"] is None:
        return "–"
    sign = "+" if stat["mean"] >= 0 else ""
    clear = stat["ci_low"] > 0 or stat["ci_high"] < 0
    mark = " **" if clear else ""
    return f"{sign}{stat['mean']:.2f} [{stat['ci_low']:+.2f}, {stat['ci_high']:+.2f}]{mark}"


def metric_table(blocks: dict[str, dict], metrics: list[str]) -> list[str]:
    lines = ["| Condition | " + " | ".join(LABELS[m] for m in metrics) + " |"]
    lines.append("|---" * (len(metrics) + 1) + "|")
    for name, block in blocks.items():
        lines.append(f"| {name} | " + " | ".join(fmt(block[m]) for m in metrics) + " |")
    return lines


def build_report(runs: dict[str, dict], seed: int = 42) -> str:
    any_run = next(iter(runs.values()))
    config = any_run["config"]
    lines = [
        "# Results",
        "",
        "Generated by `python -m musicteacher.evaluation.report` from the JSON files in "
        "`evals/results/`. Mean and 95% bootstrap confidence interval (1,000 resamples).",
        "",
        f"- Questions: {any_run['n_questions']} (split `{any_run['split']}`); generator "
        f"`{config['generator_model']}`, judge `{config['judge_model']}`, top_k {config['top_k']}, "
        f"temperature {config['temperature']}.",
        "- Retrieval metrics: QA questions only (agentic questions have no source passage). "
        "Faithfulness: QA questions with retrieved context only (not defined for C0).",
        "",
        "## Main table",
        "",
    ]
    names = {c: f"{c} ({runs[c]['retrieval_mode'] or 'no retrieval'})" for c in runs}
    lines += metric_table({names[c]: r["metrics"]["overall"] for c, r in runs.items()}, METRICS)

    lines += [
        "",
        "## Paired differences (same questions)",
        "",
        "Mean per-question difference A − B with its 95% CI. ** = the CI excludes 0.",
        "",
    ]
    diff_metrics = ["recall_at_5", "mrr_at_10", "correctness", "faithfulness"]
    lines.append("| Comparison | " + " | ".join(LABELS[m] for m in diff_metrics) + " |")
    lines.append("|---" * (len(diff_metrics) + 1) + "|")
    for a, b, label in COMPARISONS:
        if a in runs and b in runs:
            cells = [fmt_diff(paired_difference(runs[a], runs[b], m, seed)) for m in diff_metrics]
            lines.append(f"| {a} − {b} ({label}) | " + " | ".join(cells) + " |")

    answer_metrics = ["correctness", "faithfulness", "recall_at_5"]
    for title, key in [("By language", "by_lang"), ("By question type", "by_qtype")]:
        lines += ["", f"## {title}", ""]
        groups = sorted({g for r in runs.values() for g in r["metrics"][key]})
        for group in groups:
            lines += ["", f"### {group}", ""]
            blocks = {
                names[c]: r["metrics"][key][group]
                for c, r in runs.items()
                if group in r["metrics"][key]
            }
            lines += metric_table(blocks, answer_metrics)

    lines += ["", "## Cross-lingual subset (question and passage in different languages)", ""]
    lines += metric_table(
        {names[c]: r["metrics"]["cross_lingual"] for c, r in runs.items()}, answer_metrics
    )

    lines += ["", "## Dev vs held-out", ""]
    for split in ("dev", "heldout"):
        blocks = {}
        for c, r in runs.items():
            rows = [q for q in r["questions"] if q["split"] == split]
            blocks[names[c]] = summarise(rows, METRICS, seed=seed)["overall"]
        lines += ["", f"### {split}", ""]
        lines += metric_table(blocks, answer_metrics)

    lines += [
        "",
        "## Cost",
        "",
        "| Condition | Mean generation latency (s) | Judge invalid | File |",
    ]
    lines.append("|---|---|---|---|")
    for c, r in runs.items():
        latencies = [q["gen_latency_s"] for q in r["questions"]]
        lines.append(
            f"| {names[c]} | {np.mean(latencies):.1f} | {r['judge_invalid']} | `{r['_file']}` |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    settings = get_settings()
    results_dir = settings.evals_dir / "results"
    runs = latest_full_runs(results_dir)
    if not runs:
        raise SystemExit("No full run found in evals/results/ (runs with --limit are ignored).")
    report = build_report(runs, seed=settings.seed)
    out = results_dir / "report.md"
    out.write_text(report, encoding="utf-8")
    print(report)
    print(f"Saved {out}")


if __name__ == "__main__":
    main()
