"""Build the results report from the run JSONs in `evals/results/`.

For each condition, the most recent full run (no --limit) is used. The report shows:
- the main table: every metric per condition, mean and 95% bootstrap CI;
- breakdowns per language, per question type, cross-lingual subset, and dev vs held-out;
- paired differences for the research questions (same questions, two conditions): the bootstrap CI
  of the mean per-question difference. If it contains 0, the gap is not distinguishable from noise.

Every number comes from the JSON files: nothing is typed by hand.

Usage: uv run python -m musicteacher.evaluation.report [--readme]
    --readme also rewrites the results block of README.md (between the results:start and
    results:end markers) and copies the corpus statistics to evals/results/corpus_stats.json.
"""

import argparse
import json
from pathlib import Path

import numpy as np

from musicteacher.config import get_settings
from musicteacher.evaluation.metrics import bootstrap_ci, summarise
from musicteacher.evaluation.run import CONDITIONS, METRICS

# C5 = agent with tools, C5b = same agent asked once to call a tool (evaluation/run_agent.py)
ALL_CONDITIONS = [*CONDITIONS, "C5", "C5b"]
COMPARISONS = [
    ("C1", "C0", "RAG (dense) vs no retrieval"),
    ("C3", "C1", "H1: hybrid vs dense"),
    ("C2", "C1", "BM25 vs dense"),
    ("C4", "C3", "H2: reranker on top of hybrid"),
    ("C4", "C1", "RQ1: hybrid + reranker vs dense"),
    ("C5", "C4", "agent with tools vs RAG-only"),
    ("C5b", "C5", "tool call required vs free choice"),
    ("C5b", "C4", "agent (tool required) vs RAG-only"),
]
LABELS = {
    "recall_at_5": "Recall@5",
    "article_recall_at_5": "Article recall@5",
    "mrr_at_10": "MRR@10",
    "correctness": "Correctness",
    "faithfulness": "Faithfulness",
    "relevancy": "Relevancy",
    "tool_selection": "Tool selection",
    "args_correct": "Tool arguments",
}


def latest_full_runs(results_dir: Path) -> dict[str, dict]:
    runs: dict[str, dict] = {}
    for path in sorted(results_dir.glob("C*_*.json")):
        result = json.loads(path.read_text(encoding="utf-8"))
        if result.get("limit") is None and result["condition"] in ALL_CONDITIONS:
            result["_file"] = path.name
            runs[result["condition"]] = result  # sorted by name: the latest timestamp wins
    return dict(sorted(runs.items()))


def paired_difference(
    a: dict, b: dict, metric: str, seed: int = 42, qtype: str | None = None
) -> dict:
    """Mean of (a - b) over the questions scored in both runs, with a bootstrap CI.
    `qtype` restricts the comparison to one question type (e.g. "agentic")."""
    b_values = {q["id"]: q.get(metric) for q in b["questions"]}
    diffs = [
        q[metric] - b_values[q["id"]]
        for q in a["questions"]
        if q.get(metric) is not None
        and b_values.get(q["id"]) is not None
        and (qtype is None or q["qtype"] == qtype)
    ]
    return bootstrap_ci(diffs, seed=seed)


def fmt(stat: dict) -> str:
    if stat["mean"] is None:
        return "–"
    return f"{stat['mean']:.2f} [{stat['ci_low']:.2f}, {stat['ci_high']:.2f}]"


def fmt_diff(stat: dict) -> str:
    if stat["mean"] is None:
        return "–"
    sign = "+" if stat["mean"] >= 0 else ""
    clear = stat["ci_low"] > 0 or stat["ci_high"] < 0
    mark = " **" if clear else ""
    return f"{sign}{stat['mean']:.2f} [{stat['ci_low']:+.2f}, {stat['ci_high']:+.2f}]{mark}"


def metric_table(blocks: dict[str, dict], metrics: list[str]) -> list[str]:
    lines = ["| Condition | " + " | ".join(LABELS[m] for m in metrics) + " |"]
    lines.append("|---" * (len(metrics) + 1) + "|")
    for name, block in blocks.items():
        lines.append(f"| {name} | " + " | ".join(fmt(block[m]) for m in metrics) + " |")
    return lines


def build_report(runs: dict[str, dict], seed: int = 42) -> str:
    any_run = next(iter(runs.values()))
    config = any_run["config"]
    lines = [
        "# Results",
        "",
        "Generated by `python -m musicteacher.evaluation.report` from the JSON files in "
        "`evals/results/`. Mean and 95% bootstrap confidence interval (1,000 resamples).",
        "",
        f"- Questions: {any_run['n_questions']} (split `{any_run['split']}`); generator "
        f"`{config['generator_model']}`, judge `{config['judge_model']}`, top_k {config['top_k']}, "
        f"temperature {config['temperature']}.",
        "- Retrieval metrics: QA questions only (agentic questions have no source passage). "
        "Faithfulness: QA questions with retrieved context only (not defined for C0).",
        "",
        "## Main table",
        "",
    ]
    names = {c: f"{c} ({runs[c]['retrieval_mode'] or 'no retrieval'})" for c in runs}
    lines += metric_table({names[c]: r["metrics"]["overall"] for c, r in runs.items()}, METRICS)

    lines += [
        "",
        "## Paired differences (same questions)",
        "",
        "Mean per-question difference A − B with its 95% CI. ** = the CI excludes 0.",
        "",
    ]
    diff_metrics = ["recall_at_5", "mrr_at_10", "correctness", "faithfulness"]
    lines.append("| Comparison | " + " | ".join(LABELS[m] for m in diff_metrics) + " |")
    lines.append("|---" * (len(diff_metrics) + 1) + "|")
    for a, b, label in COMPARISONS:
        if a in runs and b in runs:
            cells = [fmt_diff(paired_difference(runs[a], runs[b], m, seed)) for m in diff_metrics]
            lines.append(f"| {a} − {b} ({label}) | " + " | ".join(cells) + " |")

    answer_metrics = ["correctness", "faithfulness", "recall_at_5"]
    for title, key in [("By language", "by_lang"), ("By question type", "by_qtype")]:
        lines += ["", f"## {title}", ""]
        groups = sorted({g for r in runs.values() for g in r["metrics"][key]})
        for group in groups:
            lines += ["", f"### {group}", ""]
            blocks = {
                names[c]: r["metrics"][key][group]
                for c, r in runs.items()
                if group in r["metrics"][key]
            }
            lines += metric_table(blocks, answer_metrics)

    lines += ["", "## Cross-lingual subset (question and passage in different languages)", ""]
    lines += metric_table(
        {names[c]: r["metrics"]["cross_lingual"] for c, r in runs.items()}, answer_metrics
    )

    lines += ["", "## Dev vs held-out", ""]
    for split in ("dev", "heldout"):
        blocks = {}
        for c, r in runs.items():
            rows = [q for q in r["questions"] if q["split"] == split]
            blocks[names[c]] = summarise(rows, METRICS, seed=seed)["overall"]
        lines += ["", f"### {split}", ""]
        lines += metric_table(blocks, answer_metrics)

    for agent in ("C5", "C5b"):
        if agent in runs:
            lines += agent_section(runs, seed, agent)

    lines += [
        "",
        "## Cost",
        "",
        "| Condition | Mean generation latency (s) | Judge invalid | File |",
    ]
    lines.append("|---|---|---|---|")
    for c, r in runs.items():
        latencies = [q["gen_latency_s"] for q in r["questions"]]
        lines.append(
            f"| {names[c]} | {np.mean(latencies):.1f} | {r['judge_invalid']} | `{r['_file']}` |"
        )
    return "\n".join(lines) + "\n"


def agent_section(runs: dict[str, dict], seed: int, agent: str = "C5") -> list[str]:
    """RQ3: does the agent with tools beat RAG-only on computation (agentic) questions?"""
    c5 = runs[agent]
    lines = [
        "",
        f"## Agent with tools ({agent})",
        "",
        "| Subset | Tool selection | Tool arguments | Correctness |",
    ]
    lines.append("|---|---|---|---|")
    for label, rows in [
        ("Agentic questions", [q for q in c5["questions"] if q["qtype"] == "agentic"]),
        ("QA questions", [q for q in c5["questions"] if q["qtype"] != "agentic"]),
    ]:
        block = summarise(rows, ["tool_selection", "args_correct", "correctness"], seed=seed)
        stats = block["overall"]
        lines.append(
            f"| {label} (n={len(rows)}) | {fmt(stats['tool_selection'])} | "
            f"{fmt(stats['args_correct'])} | {fmt(stats['correctness'])} |"
        )
    lines += ["", "Correctness on agentic questions, paired with the same questions (RQ3):", ""]
    lines.append("| Comparison | Correctness difference |")
    lines.append("|---|---|")
    for other in ("C4", "C0"):
        if other in runs:
            diff = paired_difference(c5, runs[other], "correctness", seed, qtype="agentic")
            lines.append(f"| {agent} − {other} (agentic only) | {fmt_diff(diff)} |")
    stopped: dict[str, int] = {}
    for q in c5["questions"]:
        stopped[q["agent_stopped"]] = stopped.get(q["agent_stopped"], 0) + 1
    lines += [
        "",
        "Agent stop reasons: " + ", ".join(f"{k} {v}" for k, v in sorted(stopped.items())),
    ]
    return lines


README_START = "<!-- results:start -->"
README_END = "<!-- results:end -->"
README_METRICS = ["recall_at_5", "mrr_at_10", "correctness", "faithfulness"]
README_COMPARISONS = [
    ("C3", "C1", "H1 hybrid vs dense"),
    ("C4", "C3", "H2 reranker on top of hybrid"),
    ("C4", "C1", "RQ1 hybrid + reranker vs dense"),
    ("C1", "C0", "retrieval vs no retrieval"),
    ("C5b", "C4", "agent (tool required) vs RAG-only"),
    ("C5b", "C5", "tool required vs free choice"),
]


def readme_block(runs: dict[str, dict], corpus: dict | None, judge: dict | None, seed: int) -> str:
    """The README results section; every number is read from evals/results/."""
    any_run = next(iter(runs.values()))
    names = {c: f"{c} ({runs[c]['retrieval_mode'] or 'no retrieval'})" for c in runs}
    lines = [
        "<!-- Generated by `python -m musicteacher.evaluation.report --readme`. Do not edit. -->",
        "",
    ]
    if corpus:
        lines += [
            f"Corpus: {corpus['articles']} Wikipedia articles, {corpus['chunks']} chunks "
            f"({corpus['chunks_en']} EN / {corpus['chunks_fr']} FR), "
            f"{corpus['chunk_tokens_total']:,} tokens. "
            f"Evaluation set: {any_run['n_questions']} questions. "
            "Mean and 95% bootstrap confidence interval.",
            "",
        ]
    lines += metric_table(
        {names[c]: r["metrics"]["overall"] for c, r in runs.items()}, README_METRICS
    )
    lines += [
        "",
        "Paired differences on the same questions (A − B, 95% CI; ** = the interval excludes 0):",
        "",
        "| Comparison | Recall@5 | Correctness | Faithfulness |",
        "|---|---|---|---|",
    ]
    for a, b, label in README_COMPARISONS:
        if a in runs and b in runs:
            cells = [
                fmt_diff(paired_difference(runs[a], runs[b], m, seed))
                for m in ("recall_at_5", "correctness", "faithfulness")
            ]
            lines.append(f"| {a} − {b}: {label} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Computation questions (transposition, interval, key), correctness and tool use:",
        "",
        "| Condition | Correctness | Tool selection | Tool arguments |",
        "|---|---|---|---|",
    ]
    for c, r in runs.items():
        block = r["metrics"]["by_qtype"].get("agentic", {})
        if "correctness" not in block:
            continue
        cells = [fmt(block["correctness"])]
        cells += [fmt(block[m]) if m in block else "–" for m in ("tool_selection", "args_correct")]
        lines.append(f"| {names[c]} | " + " | ".join(cells) + " |")
    if judge:
        rates = [
            f"{label} {judge[key]['ok']}/{judge[key]['n']}"
            for key, label in [
                ("fabrication_caught", "planted fabrications caught"),
                ("verbatim_accepted", "verbatim answers accepted"),
                ("swapped_answer_caught", "swapped answers caught"),
            ]
        ]
        lines += ["", f"Judge sanity check ({judge['judge_model']}): " + ", ".join(rates) + "."]
    return "\n".join(lines)


def update_readme(path: Path, block: str) -> None:
    text = path.read_text(encoding="utf-8")
    if README_START not in text or README_END not in text:
        raise SystemExit(f"{path} has no {README_START} ... {README_END} markers")
    before, rest = text.split(README_START, 1)
    _, after = rest.split(README_END, 1)
    path.write_text(f"{before}{README_START}\n{block}\n{README_END}{after}", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the results report.")
    parser.add_argument("--readme", action="store_true", help="also update README.md")
    args = parser.parse_args()
    settings = get_settings()
    results_dir = settings.evals_dir / "results"
    runs = latest_full_runs(results_dir)
    if not runs:
        raise SystemExit("No full run found in evals/results/ (runs with --limit are ignored).")
    report = build_report(runs, seed=settings.seed)
    out = results_dir / "report.md"
    out.write_text(report, encoding="utf-8")
    print(report)
    print(f"Saved {out}")

    if args.readme:
        corpus_src = settings.data_dir / "index" / "index_stats.json"
        corpus_out = results_dir / "corpus_stats.json"
        if corpus_src.exists():  # data/index is not versioned: keep a copy next to the results
            corpus_out.write_text(corpus_src.read_text(encoding="utf-8"), encoding="utf-8")
        corpus = json.loads(corpus_out.read_text(encoding="utf-8")) if corpus_out.exists() else None
        judge_path = results_dir / "judge_check.json"
        judge = json.loads(judge_path.read_text(encoding="utf-8")) if judge_path.exists() else None
        readme = settings.data_dir.parent / "README.md"
        update_readme(readme, readme_block(runs, corpus, judge, settings.seed))
        print(f"Updated {readme}")


if __name__ == "__main__":
    main()
